import { readFileSync } from 'node:fs';
const D = '/home/user/schluesseldienst/.cache/endstand-nach/ersatz/';
const m = JSON.parse(readFileSync(D + 'tastatur-mobil-ersatz.json', 'utf8'));
const d = JSON.parse(readFileSync(D + 'tastatur-desktop-ersatz.json', 'utf8'));
const alt = JSON.parse(readFileSync(D + 'alt-frueher-tastatur-mobil-ersatz.json', 'utf8'));
const blattStopp = (z) => z.protokoll.filter((p) => p.zweck === 'Blatt Anruf').at(-1);
const bs = blattStopp(m), bsAlt = blattStopp(alt);
const pick = (f) => f && { tag: f.tag, href: f.href, text: f.text, rect: f.rect, imSichtfeld: f.imSichtfeld, inDialog: f.inDialog, fokusSichtbar: f.fokusSichtbar, ringQuelle: f.ringQuelle, outlineStil: f.outlineStil, outlineBreite: f.outlineBreite, schatten: f.schatten };
console.log('Blatt Anruf neu:', JSON.stringify(pick(bs)));
console.log('Blatt Anruf frueher:', JSON.stringify(pick(bsAlt)));
console.log('Mobil erster Anruf je Seite (Text, Bereich):');
for (const x of m.ergebnis.h1.slice(0, 3)) console.log(' ', x.pfad, x.anrufText);
const ersterAnruf = (z) => z.protokoll.filter((p) => p.zweck.startsWith('H1 ')).filter((p, i, arr) => p.zweck !== arr[i - 1]?.zweck || true).find((p) => p.href?.startsWith('tel:') && p.zweck === 'H1 /');
console.log('Startseite Anruf mobil:', JSON.stringify(pick(ersterAnruf(m))));
console.log('Startseite Anruf desktop:', JSON.stringify(pick(ersterAnruf(d))));
