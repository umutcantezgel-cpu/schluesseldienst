console.log('Desktop H1 Stopps bis Anruf auf Startseite:', d.protokoll.filter((p) => p.zweck === 'H1 /').map((p) => `${p.schritt}:${p.tag}${p.href ? '[' + p.href + ']' : ''}`).join(' '));
console.log('Mobil H1 Stopps bis Anruf auf Startseite:', m.protokoll.filter((p) => p.zweck === 'H1 /').map((p) => `${p.schritt}:${p.tag}${p.href ? '[' + p.href + ']' : ''}`).join(' '));
console.log('Desktop ringQuellen:', JSON.stringify(d.ringQuellen), 'Mobil ringQuellen:', JSON.stringify(m.ringQuellen));
